import Link from "next/link";
import { redirect, notFound } from "next/navigation";
import { getAuthContext } from "@/lib/auth";
import { getActiveEntity } from "@/lib/active-entity";
import { formatCents } from "@/lib/accounting/ledger";
import { getW2ForEmployee } from "@/lib/accounting/year-end-forms";
import { PrintButton } from "../../PrintButton";

export const dynamic = "force-dynamic";

export default async function W2Detail({
  params,
  searchParams,
}: {
  params: { tenant: string; employeeId: string };
  searchParams: { year?: string };
}) {
  const auth = await getAuthContext(params.tenant);
  if (!auth) redirect(`/${params.tenant}/login`);

  const entity = await getActiveEntity({ tenantId: auth.tenant.id, tenantSlug: params.tenant });
  if (!entity) redirect(`/${params.tenant}/books`);

  const year = Number(searchParams.year) || new Date().getUTCFullYear() - 1;
  const w2 = await getW2ForEmployee({
    tenantId: auth.tenant.id,
    entityId: entity.id,
    employeeId: params.employeeId,
    year,
  });
  if (!w2) notFound();

  const Box = ({ num, label, value }: { num: string; label: string; value: bigint | string }) => (
    <div className="border border-slate-300 p-2">
      <p className="text-[9px] uppercase tracking-wider text-slate-500">{num} — {label}</p>
      <p className="mt-1 text-sm font-medium tabular-nums">
        {typeof value === "string" ? value : formatCents(value)}
      </p>
    </div>
  );

  return (
    <div className="mx-auto max-w-3xl p-6 print:p-0">
      <style>{`
        @media print {
          .no-print { display: none !important; }
          body { background: white; }
        }
        @page { size: letter; margin: 0.5in; }
      `}</style>

      <div className="no-print mb-4 flex items-center justify-between text-sm text-slate-500">
        <Link
          href={`/${params.tenant}/payroll/forms/w2?year=${year}`}
          className="hover:text-slate-700"
        >
          ← W-2 list
        </Link>
        <PrintButton />
      </div>

      <div className="rounded-lg border border-slate-300 bg-white p-6">
        <div className="flex items-start justify-between border-b border-slate-300 pb-3">
          <div>
            <p className="text-xs uppercase tracking-wider text-slate-500">
              Form W-2 — Wage &amp; Tax Statement
            </p>
            <h1 className="text-xl font-bold text-slate-900">Tax year {year}</h1>
          </div>
          <div className="text-right text-xs text-slate-500">
            <p>Generated by KOBIA Payroll</p>
            <p className="mt-1">For internal review — not a substitute for IRS Copy A.</p>
          </div>
        </div>

        <div className="mt-4 grid grid-cols-2 gap-4 text-sm">
          <div className="border border-slate-300 p-3">
            <p className="text-[9px] uppercase tracking-wider text-slate-500">Employer</p>
            <p className="mt-1 font-medium text-slate-900">{entity.name}</p>
          </div>
          <div className="border border-slate-300 p-3">
            <p className="text-[9px] uppercase tracking-wider text-slate-500">Employee</p>
            <p className="mt-1 font-medium text-slate-900">
              {w2.firstName} {w2.lastName}
            </p>
            {w2.ssnLast4 && (
              <p className="text-xs text-slate-500">SSN: •••-••-{w2.ssnLast4}</p>
            )}
            {w2.homeAddress && (
              <p className="text-xs text-slate-500">{w2.homeAddress}</p>
            )}
          </div>
        </div>

        <div className="mt-4 grid grid-cols-2 gap-2">
          <Box num="1" label="Wages, tips, other compensation" value={w2.totals.wagesCents} />
          <Box num="2" label="Federal income tax withheld" value={w2.totals.federalTaxCents} />
          <Box num="3" label="Social Security wages" value={w2.totals.ssWagesCents} />
          <Box num="4" label="Social Security tax withheld" value={w2.totals.ssTaxCents} />
          <Box num="5" label="Medicare wages and tips" value={w2.totals.medicareWagesCents} />
          <Box num="6" label="Medicare tax withheld" value={w2.totals.medicareTaxCents} />
          <Box num="16" label="State wages, tips, etc." value={w2.totals.stateWagesCents} />
          <Box num="17" label="State income tax" value={w2.totals.stateTaxCents} />
        </div>

        <p className="mt-4 text-[10px] text-slate-400">
          Amounts are aggregated from posted paystubs. Reconcile against year-end payroll reports
          before filing IRS Copy A or distributing copies to employees.
        </p>
      </div>
    </div>
  );
}
